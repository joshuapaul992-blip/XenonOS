#!/bin/sh
# SPDX-License-Identifier: MIT
# Build a bootable XenonOS hard-disk image.
#
#   usage: tools/mkimage.sh <kernel.elf> <output.img>
#
# Layout (MBR):
#   sectors 0..2047    MBR + Limine BIOS stage 2
#   partition 1        FAT32 "XENON", type 0x0C, active  -> drive C:
#
# C: holds both the BIOS (boot/limine/limine-bios.sys) and the UEFI
# (EFI/BOOT/BOOTX64.EFI) loaders, so the same image boots either way.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
KERNEL=$1
IMG=$2
DISK_MB=${DISK_MB:-128}
LIMINE=$ROOT/third_party/limine
VERSION=$(tr -d ' \n' < "$ROOT/VERSION")
BUILD=$(tr -d ' \n' < "${BUILD_NUMBER_FILE:-$ROOT/BUILD_NUMBER}")
TITLE="XenonOS $VERSION (build $BUILD)"

for tool in sfdisk mkfs.fat mmd mcopy; do
    command -v $tool >/dev/null 2>&1 || { echo "mkimage: '$tool' not found (install dosfstools, mtools, fdisk)" >&2; exit 1; }
done
[ -x "$LIMINE/limine" ] || make -C "$LIMINE" -s >/dev/null

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
PART=$WORK/c.img
PART_START=2048                                  # 1 MiB
PART_SECTORS=$(( DISK_MB * 2048 - PART_START ))

# limine.conf
cat > "$WORK/limine.conf" <<CONF
# XenonOS boot menu - generated by tools/mkimage.sh
timeout: 3
interface_branding: XenonOS Boot Manager

/$TITLE
    protocol: limine
    path: boot():/XenonOS/System/xnkrnl.elf
    cmdline:
CONF

printf 'xenon\n' > "$WORK/hostname"
printf '%s\n' "$TITLE" > "$WORK/version.txt"

# FAT32 file system for C:
rm -f "$PART"
mkfs.fat -C -F 32 -n XENON -h $PART_START -S 512 "$PART" $(( PART_SECTORS / 2 )) >/dev/null
export MTOOLS_SKIP_CHECK=1
M="-i $PART"
mmd $M ::/boot ::/boot/limine ::/EFI ::/EFI/BOOT
mmd $M ::/XenonOS ::/XenonOS/System ::/XenonOS/System/Drivers ::/XenonOS/Bin ::/XenonOS/Config ::/XenonOS/Logs
mcopy $M "$LIMINE/limine-bios.sys" "$WORK/limine.conf" ::/boot/limine/
mcopy $M "$LIMINE/BOOTX64.EFI" ::/EFI/BOOT/
mcopy $M "$KERNEL" ::/XenonOS/System/xnkrnl.elf
mcopy $M "$WORK/hostname" ::/XenonOS/Config/hostname
mcopy $M "$WORK/version.txt" ::/XenonOS/version.txt

# Disk with an MBR partition table
rm -f "$IMG"
truncate -s ${DISK_MB}M "$IMG"
printf 'label: dos\nstart=%s, size=%s, type=c, bootable\n' $PART_START $PART_SECTORS | sfdisk -q "$IMG"
dd if="$PART" of="$IMG" bs=512 seek=$PART_START conv=notrunc,sparse status=none
"$LIMINE/limine" bios-install "$IMG" >/dev/null 2>&1 || { "$LIMINE/limine" bios-install "$IMG"; exit 1; }

echo "mkimage: $IMG ($DISK_MB MiB) - $TITLE"

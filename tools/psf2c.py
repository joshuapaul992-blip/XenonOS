#!/usr/bin/env python3
"""Convert a PSF1/PSF2 console font into a XenonOS kernel font (C source).

The output contains 256 glyphs laid out in Code Page 437 order, so the kernel
console can draw CP437 characters (box drawing, blocks, accented letters)
directly. Unicode code points are mapped to CP437 by the console at run time.

usage: psf2c.py <font.psf[.gz]> <symbol_name> <output.c>
"""
import gzip
import struct
import sys

# Unicode code point for each CP437 byte value.
CP437 = (
    [0x0000, 0x263A, 0x263B, 0x2665, 0x2666, 0x2663, 0x2660, 0x2022,
     0x25D8, 0x25CB, 0x25D9, 0x2642, 0x2640, 0x266A, 0x266B, 0x263C,
     0x25BA, 0x25C4, 0x2195, 0x203C, 0x00B6, 0x00A7, 0x25AC, 0x21A8,
     0x2191, 0x2193, 0x2192, 0x2190, 0x221F, 0x2194, 0x25B2, 0x25BC]
    + list(range(0x20, 0x7F)) + [0x2302] +
    [0x00C7, 0x00FC, 0x00E9, 0x00E2, 0x00E4, 0x00E0, 0x00E5, 0x00E7,
     0x00EA, 0x00EB, 0x00E8, 0x00EF, 0x00EE, 0x00EC, 0x00C4, 0x00C5,
     0x00C9, 0x00E6, 0x00C6, 0x00F4, 0x00F6, 0x00F2, 0x00FB, 0x00F9,
     0x00FF, 0x00D6, 0x00DC, 0x00A2, 0x00A3, 0x00A5, 0x20A7, 0x0192,
     0x00E1, 0x00ED, 0x00F3, 0x00FA, 0x00F1, 0x00D1, 0x00AA, 0x00BA,
     0x00BF, 0x2310, 0x00AC, 0x00BD, 0x00BC, 0x00A1, 0x00AB, 0x00BB,
     0x2591, 0x2592, 0x2593, 0x2502, 0x2524, 0x2561, 0x2562, 0x2556,
     0x2555, 0x2563, 0x2551, 0x2557, 0x255D, 0x255C, 0x255B, 0x2510,
     0x2514, 0x2534, 0x252C, 0x251C, 0x2500, 0x253C, 0x255E, 0x255F,
     0x255A, 0x2554, 0x2569, 0x2566, 0x2560, 0x2550, 0x256C, 0x2567,
     0x2568, 0x2564, 0x2565, 0x2559, 0x2558, 0x2552, 0x2553, 0x256B,
     0x256A, 0x2518, 0x250C, 0x2588, 0x2584, 0x258C, 0x2590, 0x2580,
     0x03B1, 0x00DF, 0x0393, 0x03C0, 0x03A3, 0x03C3, 0x00B5, 0x03C4,
     0x03A6, 0x0398, 0x03A9, 0x03B4, 0x221E, 0x03C6, 0x03B5, 0x2229,
     0x2261, 0x00B1, 0x2265, 0x2264, 0x2320, 0x2321, 0x00F7, 0x2248,
     0x00B0, 0x2219, 0x00B7, 0x221A, 0x207F, 0x00B2, 0x25A0, 0x00A0]
)
assert len(CP437) == 256


BLOCKS = (0x2593, 0x2584, 0x258C, 0x2590, 0x2580)


def block_glyph(cp, width, height, rowbytes):
    """Draw block/shade characters some fonts leave out."""
    out = bytearray()
    for y in range(height):
        bits = 0
        for x in range(width):
            on = {
                0x2593: (x + y) % 4 != 0,          # dark shade
                0x2584: y >= height // 2,          # lower half
                0x258C: x < width // 2,            # left half
                0x2590: x >= width // 2,           # right half
                0x2580: y < height // 2,           # upper half
            }[cp]
            if on:
                bits |= 1 << (rowbytes * 8 - 1 - x)
        out += bits.to_bytes(rowbytes, "big")
    return bytes(out)


def load_psf(path):
    raw = open(path, "rb").read()
    if raw[:2] == b"\x1f\x8b":
        raw = gzip.decompress(raw)
    umap = {}
    if raw[:2] == b"\x36\x04":                      # PSF1
        mode, charsize = raw[2], raw[3]
        count = 512 if mode & 1 else 256
        width, height, bpg = 8, charsize, charsize
        glyphs = raw[4:4 + count * bpg]
        table = raw[4 + count * bpg:]
        if mode & 2:
            pos = 0
            for g in range(count):
                while pos + 1 < len(table):
                    cp = struct.unpack_from("<H", table, pos)[0]
                    pos += 2
                    if cp == 0xFFFF:
                        break
                    if cp == 0xFFFE:
                        continue
                    umap.setdefault(cp, g)
    elif raw[:4] == b"\x72\xb5\x4a\x86":            # PSF2
        (_, _, hdrsize, flags, count, bpg, height, width) = struct.unpack_from("<8I", raw, 0)
        glyphs = raw[hdrsize:hdrsize + count * bpg]
        table = raw[hdrsize + count * bpg:]
        if flags & 1:
            g = 0
            for entry in table.split(b"\xff")[:count]:
                seqs = entry.split(b"\xfe")
                for ch in seqs[0].decode("utf-8", "ignore"):
                    umap.setdefault(ord(ch), g)
                g += 1
    else:
        sys.exit(f"{path}: not a PSF font")
    return width, height, bpg, glyphs, umap


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, name, out = sys.argv[1:]
    width, height, bpg, glyphs, umap = load_psf(src)
    rowbytes = (width + 7) // 8
    missing = []
    lines = [
        "/* Generated by tools/psf2c.py - do not edit.",
        " *",
        " * Terminus Font, Copyright (c) 2010 Dimitar Toshkov Zhekov.",
        " * Licensed under the SIL Open Font License 1.1;",
        " * see third_party/fonts/terminus/LICENSE.",
        " */",
        '#include "font.h"',
        "",
        f"static const unsigned char glyphs[256 * {rowbytes * height}] = {{",
    ]
    for i, cp in enumerate(CP437):
        g = umap.get(cp)
        if g is None:
            g = umap.get(0xFFFD, umap.get(ord("?")))
            if i >= 0x20:
                missing.append(f"{i:02X}")
        data = glyphs[g * bpg:(g + 1) * bpg] if g is not None else bytes(bpg)
        if cp in BLOCKS and cp not in umap:
            data = block_glyph(cp, width, height, rowbytes)
            if missing and missing[-1] == f"{i:02X}":
                missing.pop()
        if i == 0:
            data = bytes(bpg)
        lines.append("    " + ",".join(f"0x{b:02x}" for b in data[:rowbytes * height]) + f",  /* {i:02X} */")
    lines += [
        "};",
        "",
        f"const struct KFONT {name} = {{",
        f"    .Width = {width}, .Height = {height}, .BytesPerRow = {rowbytes},",
        "    .Glyphs = glyphs,",
        "};",
        "",
    ]
    open(out, "w").write("\n".join(lines))
    if missing:
        print(f"psf2c: {name}: no glyph for CP437 {' '.join(missing)}", file=sys.stderr)


if __name__ == "__main__":
    main()
